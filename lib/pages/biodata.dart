import 'package:flutter/material.dart';

class Biodata extends StatelessWidget {
  const Biodata({super.key});

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: Colors.grey[100],

      appBar: AppBar(
        automaticallyImplyLeading: false,
        backgroundColor: Colors.orange,
        title: const Text(
          "Mobile App Class",
          style: TextStyle(
            color: Colors.white,
            fontWeight: FontWeight.bold,
          ),
        ),
        centerTitle: true,
      ),

      body: SingleChildScrollView(
        child: Padding(
          padding: const EdgeInsets.all(20),
          child: Column(
            children: [
              const SizedBox(height: 10),

              Image.asset(
                "images/logo.png",
                width: 120,
                height: 120,
              ),

              const SizedBox(height: 10),

              const Text(
                "BIODATA",
                style: TextStyle(
                  fontSize: 22,
                  fontWeight: FontWeight.bold,
                  color: Colors.orange,
                ),
              ),

              const SizedBox(height: 20),

              Row(
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  foto("images/img 2.png"),
                  const SizedBox(width: 10),
                  foto("images/img 3.png"),
                  const SizedBox(width: 10),
                  foto("images/img 4.png"),
                  const SizedBox(width: 10),
                  foto("images/img 5.png"),
                ],
              ),

              const SizedBox(height: 15),

              Row(
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  foto("images/img 6.png"),
                  const SizedBox(width: 10),
                  foto("images/img 7.png"),
                  const SizedBox(width: 10),
                  foto("images/img 8.png"),
                  const SizedBox(width: 10),
                  foto("images/img 9.png"),
                ],
              ),
            ],
          ),
        ),
      ),

      bottomNavigationBar: BottomNavigationBar(
        type: BottomNavigationBarType.fixed,
        backgroundColor: Colors.white,
        selectedItemColor: Colors.orange,
        unselectedItemColor: Colors.orange,
        currentIndex: 0,

        onTap: (index) {
          if (index == 0) {
            Navigator.pushNamed(context, "/beranda");
          } else if (index == 1) {
            ScaffoldMessenger.of(context).showSnackBar(
              const SnackBar(
                content: Text("Menu Kontak belum tersedia"),
              ),
            );
          } else if (index == 2) {
            ScaffoldMessenger.of(context).showSnackBar(
              const SnackBar(
                content: Text("Menu Browser belum tersedia"),
              ),
            );
          } else if (index == 3) {
            Navigator.pop(context);
          }
        },

        items: const [
          BottomNavigationBarItem(
            icon: Icon(Icons.home),
            label: "Home",
          ),
          BottomNavigationBarItem(
            icon: Icon(Icons.contact_page),
            label: "Kontak",
          ),
          BottomNavigationBarItem(
            icon: Icon(Icons.language),
            label: "Browser",
          ),
          BottomNavigationBarItem(
            icon: Icon(Icons.arrow_back),
            label: "Kembali",
          ),
        ],
      ),
    );
  }

  Widget foto(String gambar) {
    return Container(
      width: 75,
      height: 100,
      padding: const EdgeInsets.all(3),
      decoration: BoxDecoration(
        color: Colors.white,
        border: Border.all(
          color: Colors.orange,
        ),
        borderRadius: BorderRadius.circular(10),
      ),
      child: ClipRRect(
        borderRadius: BorderRadius.circular(7),
        child: Image.asset(
          gambar,
          fit: BoxFit.contain,
        ),
      ),
    );
  }
}